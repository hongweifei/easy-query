package net.cyue.web.easyquery.core.http;

/**
 * HTTP请求方法枚举
 */
public enum HTTPRequestMethod {
    /**
     * GET方法
     */
    GET,

    /**
     * POST方法
     */
    POST,

    /**
     * PUT方法
     */
    PUT,

    /**
     * DELETE方法
     */
    DELETE,

    /**
     * PATCH方法
     */
    PATCH,

    /**
     * 所有方法
     */
    ALL,

    /**
     * OPTIONS方法
     */
    OPTIONS,

    /**
     * HEAD方法
     */
    HEAD,

    /**
     * TRACE方法
     */
    TRACE,

    /**
     * SEARCH方法
     */
    SEARCH;
}
